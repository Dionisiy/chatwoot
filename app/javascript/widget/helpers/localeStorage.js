// Язык, выбранный клиентом вручную в виджете (LocaleSwitcher.vue). Апстрим
// такого выбора не предусматривает: локаль приходит из настроек аккаунта или
// из ?locale= в адресе, и на каждой перезагрузке применяется заново. Чтобы
// выбор клиента не сбрасывался, храним его отдельно и применяем последним —
// см. app.vue#mounted.
//
// localStorage здесь свой у домена виджета, а не у сайта-хоста, поэтому
// выбор переживает переходы по страницам сайта. Обёрнуто в try/catch: в
// приватном режиме и при заблокированных сторонних куках обращение к
// localStorage из iframe бросает исключение, и виджет не должен из-за этого
// падать — просто останется локаль по умолчанию.
const KEY = 'cw_widget_locale';

export const getWidgetLocale = () => {
  try {
    return window.localStorage.getItem(KEY);
  } catch {
    return null;
  }
};

export const saveWidgetLocale = code => {
  try {
    window.localStorage.setItem(KEY, code);
  } catch {
    // выбор просто не переживёт перезагрузку — это лучше, чем упасть
  }
};
