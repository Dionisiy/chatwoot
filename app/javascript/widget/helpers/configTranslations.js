// Переводы строк, которые приходят с сервера из настроек инбокса, а не из
// словарей виджета: подпись поля pre-chat формы и список категорий
// (Settings → Inboxes → Pre-chat form). Они хранятся в базе одной строкой,
// на том языке, на котором их завёл администратор, и локали не имеют в
// принципе — поэтому украинский виджет до сих пор показывал русский список
// категорий.
//
// Ключ — ровно то значение, что лежит в настройках. Оно же уходит на сервер
// как custom_attributes.type и служит ключом маршрутизации: по нему бот
// выбирает ветку сценария (см. agent-bot-scenarios/src/engine.js →
// CATEGORY_ENTRY_NODE), по нему же собирается статистика в дашборде.
// Поэтому переводим ТОЛЬКО подпись на экране, а отправляемое значение
// оставляем нетронутым (см. Form.vue#getOptions/#getValue: FormKit хранит
// индекс варианта, а не подпись).
//
// Незнакомая строка (админ добавил новую категорию) показывается как есть —
// это заметно, но работает; молча пустой пункт списка был бы хуже.
